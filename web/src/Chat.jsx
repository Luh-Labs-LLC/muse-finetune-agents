// Try a finished fine-tune, blind: each message goes to the queue (worker.js), the dispatcher on our GPU answers it
// with the fine-tune and with the same base model told the goal (the rival the judge's headline score uses), and the
// two replies show as A and B in random order. Pick the better one and you're told which was which; your vote joins
// everyone else's, a check on the AI judge by people. Messages are answered one at a time and each on its own,
// without the earlier ones as context, the same way the judge tested the model.
//
// `subject` is a request's id, or demo:<job> for a demo model's fine-tune.
import { useEffect, useState } from "react";
import { useJson } from "./lib/data.js";

const POLL_MS = 1500;
const GIVE_UP_MS = 3 * 60_000;

// The one GPU trains requests and answers chats in turn: while a run trains, messages wait until it's done
export function Busy({ className = "" }) {
  const { data } = useJson("/api/status", 30_000);
  if (!data?.running) return null;
  return (
    <p className={`small notice-inline ${className}`} role="status">
      Chat is paused: our GPU is training a request, and replies wait until that run is done (usually 10 to 40
      minutes). A message sent now will most likely time out, so try again then.
    </p>
  );
}

export default function Chat({ subject }) {
  const [message, setMessage] = useState("");
  const [turns, setTurns] = useState([]);  // {key, id, message, flip, error}
  const [sending, setSending] = useState(false);
  const [tally, setTally] = useState(null);
  const { data: counted } = useJson(`/api/votes/${encodeURIComponent(subject)}`);

  async function send(e) {
    e.preventDefault();
    const text = message.trim();
    if (!text) return;
    setSending(true);
    const key = Date.now();
    const flip = Math.random() < 0.5;  // which side the fine-tune is on, chosen here so the page can't give it away
    try {
      const r = await fetch(`/api/requests/${encodeURIComponent(subject)}/chat`, { method: "POST",
        headers: { "Content-Type": "application/json" }, body: JSON.stringify({ message: text }) });
      const data = await r.json().catch(() => ({}));
      if (!r.ok) throw new Error(data.error ?? `the site answered ${r.status}`);
      setTurns((t) => [...t, { key, id: data.id, message: text, flip }]);
      setMessage("");
    } catch (err) {
      setTurns((t) => [...t, { key, message: text, error: err.message }]);
    } finally {
      setSending(false);
    }
  }

  return (
    <section className="tile panel chat" aria-labelledby={`chat-${subject}`}>
      <h3 id={`chat-${subject}`}>Blind test: which reply is better?</h3>
      <p className="small muted">
        Ask anything. The fine-tune and the same model just told the goal both answer, on our GPU, shown as A and B in
        a random order. Pick the better one, and we'll tell you which was which. Every vote counts toward a check on
        the AI judge. Replies are AI-generated by small models and can be wrong. Don't share personal details;
        messages are kept for 7 days.
      </p>
      <Votes tally={tally ?? counted} />
      <Busy />
      <ol className="chat-turns">
        {turns.map((t) => <Turn key={t.key} turn={t} onVoted={setTally} />)}
      </ol>
      <form className="chat-form" onSubmit={send}>
        <label className="sr-only" htmlFor={`chat-input-${subject}`}>Your message</label>
        <input id={`chat-input-${subject}`} value={message} maxLength={500} autoComplete="off"
               placeholder="Ask the model something…" onChange={(e) => setMessage(e.target.value)} />
        <button className="button primary" type="submit" disabled={sending || !message.trim()}>
          {sending ? "Sending…" : "Send"}
        </button>
      </form>
    </section>
  );
}

// People's votes so far on this fine-tune.
export function Votes({ tally }) {
  if (!tally?.total) return null;
  return (
    <p className="small votes" role="status">
      People voting blind so far: <strong>fine-tune {tally.tuned}</strong> · model told the goal {tally.rival} ·
      about the same {tally.tie} <span className="muted">({tally.total} vote{tally.total === 1 ? "" : "s"})</span>
    </p>
  );
}

function Turn({ turn, onVoted }) {
  const chat = useChat(turn.id);
  const [pick, setPick] = useState(null);  // what the visitor picked: "tuned", "rival" or "tie"
  const [problem, setProblem] = useState(null);
  const error = turn.error ?? chat?.error;
  const waiting = !error && chat?.status !== "answered";
  const sides = turn.flip ? ["tuned", "rival"] : ["rival", "tuned"];  // what A and B are
  const text = { tuned: chat?.tuned, rival: chat?.base };
  const name = { tuned: "Fine-tuned", rival: "Told the goal" };

  async function vote(p) {
    setPick(p);
    try {
      const r = await fetch(`/api/chats/${turn.id}/vote`, { method: "POST",
        headers: { "Content-Type": "application/json" }, body: JSON.stringify({ pick: p }) });
      const data = await r.json().catch(() => ({}));
      if (!r.ok) throw new Error(data.error ?? `the site answered ${r.status}`);
      onVoted(data);
    } catch (err) {
      setProblem(`Your vote wasn't counted (${err.message}).`);
    }
  }

  return (
    <li className="chat-turn">
      <p className="chat-you"><span className="sr-only">You: </span>{turn.message}</p>
      {error ? (
        <p className="form-error small" role="alert">{error}</p>
      ) : waiting ? (
        <p className="small muted" role="status">
          <span className="typing" aria-hidden="true"><i /><i /><i /></span>{" "}
          {chat?.online === false ? "No GPU is online right now; it'll answer when the machine is back."
            : chat?.status === "answering" ? "Both models are answering…"
            : "Waiting for the GPU (it may be training someone's request)…"}
        </p>
      ) : (
        <>
          <div className="pair">
            {sides.map((side, i) => (
              <figure key={side} className={pick && pick === side ? "won" : ""}>
                <figcaption>Reply {"AB"[i]}{pick && <> · <strong>{name[side]}</strong></>}</figcaption>
                <blockquote>{text[side]}</blockquote>
              </figure>
            ))}
          </div>
          {pick ? (
            <p className="small" role="status">
              {pick === "tie" ? "You called it even. " : pick === "tuned" ? "You picked the fine-tune. "
                : "You picked the model that was just told the goal. "}
              {problem && <span className="form-error">{problem}</span>}
            </p>
          ) : (
            <p className="vote-buttons">
              <button type="button" className="button" onClick={() => vote(sides[0])}>A is better</button>
              <button type="button" className="button" onClick={() => vote(sides[1])}>B is better</button>
              <button type="button" className="button" onClick={() => vote("tie")}>About the same</button>
            </p>
          )}
        </>
      )}
    </li>
  );
}

// Follows one message until both replies are in (or it fails, or nobody answers in a few minutes).
function useChat(id) {
  const [chat, setChat] = useState(null);
  useEffect(() => {
    if (!id) return;
    let stop = false;
    const started = Date.now();
    async function poll() {
      while (!stop) {
        try {
          const r = await fetch(`/api/chats/${id}`);
          const data = await r.json();
          if (!r.ok) throw new Error(data.error ?? `the site answered ${r.status}`);
          setChat(data);
          if (data.status === "answered" || data.status === "failed") return;
        } catch (err) {
          setChat({ status: "failed", error: `Couldn't check on it (${err.message}).` });
          return;
        }
        if (Date.now() - started > GIVE_UP_MS) {
          setChat({ status: "failed", error: "No answer yet; the GPU is busy. Try again in a few minutes." });
          return;
        }
        await new Promise((r) => setTimeout(r, POLL_MS));
      }
    }
    poll();
    return () => { stop = true; };
  }, [id]);
  return chat;
}
